def hg_univariate_redux(pol, modulus, beta, mm, tt, XX):
   
    dd = pol.degree()
    nn = dd * mm + tt

    if not 0 < beta <= 1:
        raise ValueError("beta should belongs in [0, 1]")

    if not pol.is_monic():
        raise ArithmeticError("Polynomial must be monic.")

    polZ = pol.change_ring(ZZ)
    x = polZ.parent().gen()

    gg = []
    for ii in range(mm):
        for jj in range(dd):
            gg.append((x * XX) ** jj * modulus ** (mm - ii) * polZ(x * XX) ** ii)
    for ii in range(tt):
        gg.append((x * XX) ** ii * polZ(x * XX) ** mm)

    BB = Matrix(ZZ, nn)
    for ii in range(nn):
        for jj in range(ii + 1):
            BB[ii, jj] = gg[ii][jj]

    BB = BB.LLL()

    new_pol = 0
    for ii in range(nn):
        new_pol += x ** ii * BB[0, ii] / XX ** ii #reverse the scaling and reconstruct the polynomial

    possible = new_pol.roots()
    roots = []

    for root in possible:
        if root[0].is_integer():
            result = polZ(ZZ(root[0]))
            if gcd(modulus, result) >= modulus ** beta:    #f(x0)≡ p (mod N) so gcd (N, f(x0))= gcd (pq, p)=p
                roots.append(ZZ(root[0]))

    return roots



def roca_solve_instance(M, n, a, m):

    from __main__ import hg_univariate_redux

    base = int(65537)
    known = int(pow(base, a, M) * inverse_mod(M, n))

    F = PolynomialRing(Zmod(n), implementation='NTL', names=('x',))
    (x,) = F._first_ngens(1)
    pol = x + known

    beta = 0.1
    t = m + 1
    XX = floor(2 * n**0.5 / M)

    roots = hg_univariate_redux(pol, n, beta, m, t, XX)

    for k in roots:
        p = int(k * M + pow(base, a, M))
        if n % p == 0:
            return p, n // p


